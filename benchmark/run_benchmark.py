"""
Benchmark EcoToxFred on the questions in test_set.json.

For every question and repetition, the agent is invoked once and three things are scored:

1. Tool selection: whether the agent called at least one of the expected tools.
2. Execution accuracy: all Cypher statements generated by CypherSearch are executed and the union of
   their results is compared to the answer columns of the human-written reference Cypher statement.
3. Goal accuracy: RAGAS AgentGoalAccuracy, judged by a separate LLM against a reference that
   combines the desired outcome with the reference query result.

Run from the repository root:
    python benchmark/run_benchmark.py --repetitions 3 --judge-model gpt-5
"""

import argparse
import asyncio
import datetime
import json
import math
import re
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import langchain_core.messages as m
from langchain_core.messages import messages_to_dict
from langchain_core.runnables import RunnableConfig
from neo4j.time import Date, DateTime
from openai import AsyncOpenAI
from ragas.llms import llm_factory
from ragas.metrics.collections import AgentGoalAccuracyWithoutReference, AgentGoalAccuracyWithReference

from agent import EcoToxFred
from config import config
from forked_convert_langchain_to_ragas import convert_to_ragas_messages
from graph import connect_to_neo4j

CYPHER_BLOCK = re.compile(r"```(?:cypher)?\s*(.*?)```", re.DOTALL)
NO_DATA = re.compile(r"No data was found for the following cypher:\s*(.*)", re.DOTALL)
MAX_REFERENCE_ROWS = 30


def normalize(value):
    """Map a database value to a comparable, hashable representation."""
    if value is None:
        return None
    if isinstance(value, bool):
        return value
    if isinstance(value, (int, float)):
        if value == 0 or math.isnan(value):
            return 0.0
        return float(f"{value:.4g}")
    if isinstance(value, (Date, DateTime, datetime.date, datetime.datetime)):
        return str(value)[:10]
    if isinstance(value, (list, tuple)):
        return tuple(normalize(v) for v in value)
    return str(value).strip().lower()


def row_values(rows, columns=None):
    if columns:
        rows = [{c: row.get(c) for c in columns} for row in rows]
    return [frozenset(normalize(v) for v in row.values()) for row in rows]


def compare(gold_rows, agent_rows, mode, answer_columns=None, last_rows=None):
    """Return (match, row_recall) of the agent result with respect to the reference result.

    Only the answer columns of the reference result are compared. A reference row is found if all its
    answer values occur together in one row of the agent result; column names are ignored. For questions
    without matching data, the last generated query, on which the answer is based, must return no rows.
    """
    if mode == "abstain":
        return (last_rows == 0, None)
    if agent_rows is None:
        return (False, 0.0)
    gold, agent = row_values(gold_rows, answer_columns), row_values(agent_rows)
    if mode == "subset_of_gold":
        gold_values = frozenset().union(*gold) if gold else frozenset()
        hits = [bool(a & gold_values) for a in agent]
        enough = len(agent) >= min(20, len(gold))
        return (bool(agent) and all(hits) and enough, sum(hits) / max(len(agent), 1))
    if mode == "any_value":
        gold_values = frozenset().union(*gold) if gold else frozenset()
        found = any(a & gold_values for a in agent)
        return (found, float(found))
    hits = [any(g <= a for a in agent) for g in gold]
    recall = sum(hits) / len(gold) if gold else 1.0
    return (all(hits), recall)


def as_text(content):
    return content if isinstance(content, str) else json.dumps(content, default=str)


def extract_cyphers(messages):
    """Return the Cypher statements of all CypherSearch calls."""
    cyphers = []
    for message in messages:
        if isinstance(message, m.ToolMessage) and message.name == "CypherSearch":
            content = as_text(message.content)
            found = NO_DATA.search(content) or CYPHER_BLOCK.search(content)
            if found:
                cyphers.append(found.group(1).strip())
    return cyphers


def execute_all(graph, cyphers):
    """Execute all generated queries and return the union of their rows, the errors, and the row count of the
    last query (None if no query was generated)."""
    rows, errors, last_rows = [], [], None
    for cypher in cyphers:
        result, error = run_query(graph, cypher)
        rows.extend(result or [])
        last_rows = len(result or [])
        if error:
            errors.append(error)
    return rows, errors, last_rows


def run_query(graph, cypher):
    try:
        return graph.query(cypher)[:1000], None
    except Exception as e:
        return None, f"{type(e).__name__}: {e}"


def build_reference(item, gold_rows):
    reference = item.get("desired_outcome") or ""
    if gold_rows is not None:
        shown = json.dumps(gold_rows[:MAX_REFERENCE_ROWS], default=str)
        reference += f"\nCorrect result according to the reference database query (first {MAX_REFERENCE_ROWS} rows): {shown}"
    return reference.strip()


async def judge(messages, reference, judge_llm):
    sanitized = []
    for message in messages:
        if isinstance(message, (m.ToolMessage, m.HumanMessage)) and not isinstance(message.content, str):
            message = message.model_copy(update={"content": as_text(message.content)})
        if isinstance(message, m.AIMessage) and not isinstance(message.content, str):
            message = message.model_copy(update={"content": as_text(message.content)})
        sanitized.append(message)
    ragas_messages = convert_to_ragas_messages(sanitized)
    if reference:
        metric = AgentGoalAccuracyWithReference(llm=judge_llm)
        result = await metric.ascore(user_input=ragas_messages, reference=reference)
    else:
        metric = AgentGoalAccuracyWithoutReference(llm=judge_llm)
        result = await metric.ascore(user_input=ragas_messages)
    return result.value


def token_usage(messages):
    total = {"input_tokens": 0, "output_tokens": 0}
    for message in messages:
        usage = getattr(message, "usage_metadata", None) or {}
        for key in total:
            total[key] += usage.get(key, 0)
    return total


async def main(args):
    tests = json.load(open(args.test_set))["tests"]
    if args.only:
        tests = [t for t in tests if t["id"] in args.only]
    if args.agent_model:
        # The agent and its tools read the model name from the configuration when they are created
        config._config["OPENAI_MODEL"] = args.agent_model
    out_dir = Path(args.out) / datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
    out_dir.mkdir(parents=True, exist_ok=True)
    meta = dict(agent_model=config["OPENAI_MODEL"], judge_model=args.judge_model, repetitions=args.repetitions,
                concurrency=args.concurrency,
                n_items=len(tests), started=datetime.datetime.now().isoformat())
    json.dump(meta, open(out_dir / "meta.json", "w"), indent=2)
    print(json.dumps(meta), flush=True)

    graph = connect_to_neo4j()
    judge_llm = llm_factory(args.judge_model, client=AsyncOpenAI(api_key=config["OPENAI_API_KEY"]), max_tokens=8192)
    gold = {t["id"]: run_query(graph, t["cypher"])[0] if t.get("cypher") else None for t in tests}

    (out_dir / "messages").mkdir()
    semaphore = asyncio.Semaphore(args.concurrency)

    async def run_one(item, rep):
        async with semaphore:
            record = dict(id=item["id"], category=item["category"], source=item["source"], repetition=rep)
            start = time.time()
            try:
                agent = EcoToxFred()
                result = await asyncio.to_thread(
                    agent.agent.invoke, {"messages": [m.HumanMessage(content=item["question"])]},
                    config=RunnableConfig(recursion_limit=50))
                messages = result["messages"]
                record["error"] = None
            except Exception as e:
                messages, record["error"] = [], f"{type(e).__name__}: {e}"
            record["latency_s"] = round(time.time() - start, 1)
            record.update(token_usage(messages))
            json.dump(messages_to_dict(messages), open(out_dir / "messages" / f"{item['id']}_rep{rep}.json", "w"),
                      default=str)
            called = [tc["name"] for msg in messages if isinstance(msg, m.AIMessage) for tc in msg.tool_calls]
            record["tools_called"] = called
            record["tool_correct"] = any(name in item["expected_tools"] for name in called)
            record["answer"] = as_text(messages[-1].content) if messages else ""

            cyphers = extract_cyphers(messages)
            record["generated_cyphers"] = cyphers
            agent_rows, query_errors, last_rows = await asyncio.to_thread(execute_all, graph, cyphers)
            record["query_errors"] = query_errors
            record["agent_rows"] = len(agent_rows)
            if item["check"] != "none" and (gold[item["id"]] is not None or item["check"] == "abstain"):
                match, recall = compare(gold[item["id"]] or [], agent_rows, item["check"], item.get("answer_columns"),
                                        last_rows)
                record["execution_match"], record["row_recall"] = match, recall
            else:
                record["execution_match"], record["row_recall"] = None, None

            try:
                reference = build_reference(item, gold[item["id"]])
                record["goal_accuracy"] = await judge(messages, reference, judge_llm) if messages else 0.0
            except Exception as e:
                record["goal_accuracy"], record["judge_error"] = None, f"{type(e).__name__}: {e}"

            print(f"{item['id']} rep{rep}: tool={record['tool_correct']} ex={record['execution_match']} "
                  f"goal={record['goal_accuracy']} {record['latency_s']}s {record['error'] or ''}", flush=True)
            return record

    records = await asyncio.gather(*(run_one(item, rep) for item in tests for rep in range(1, args.repetitions + 1)))
    with open(out_dir / "runs.jsonl", "w") as runs:
        runs.writelines(json.dumps(record, default=str) + "\n" for record in records)
    print(f"Results written to {out_dir}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--test-set", default="test_set.json")
    parser.add_argument("--repetitions", type=int, default=3)
    parser.add_argument("--judge-model", default="gpt-5")
    parser.add_argument("--agent-model", help="Overrides OPENAI_MODEL of the configuration")
    parser.add_argument("--out", default="benchmark/results")
    parser.add_argument("--only", nargs="*", help="Run only these item ids, e.g. D02 W01")
    parser.add_argument("--concurrency", type=int, default=5, help="Number of questions run in parallel")
    asyncio.run(main(parser.parse_args()))
